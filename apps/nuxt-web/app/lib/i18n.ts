const messages: Record<Locale, Dict> = { 'pt-BR': pt, 'en-US': en }

export function getLocale(): Locale {
  try {
    const saved = localStorage.getItem('hirewerk-locale')
    if (saved === 'pt-BR' || saved === 'en-US') return saved
  } catch { /* storage bloqueado */ }
  if (typeof navigator !== 'undefined' && navigator.language.startsWith('en')) return 'en-US'
  return 'pt-BR'
}

export function setLocale(locale: Locale): void {
  try { localStorage.setItem('hirewerk-locale', locale) } catch { /* ignore */ }
}

/**
 * Interpola {param} no template com os valores dados.
 *
 * Plural: chaves com `{n}` escolhem a forma singular quando n === 1, procurando
 * a variante `key.one` antes da chave base. Assim "{n} palavras" vira
 * "1 palavra" sem duplicar a lógica em cada componente.
 */
export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const dict = messages[locale] ?? messages['pt-BR']!
  const n = params?.n
  const singular = typeof n === 'number' && n === 1 ? dict[`${key}.one`] : undefined
  const template = singular ?? dict[key] ?? messages['pt-BR']?.[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (m, p) => String(params[p] ?? m))
}
